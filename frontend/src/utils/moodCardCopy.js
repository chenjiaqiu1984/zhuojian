export function getMoodCardCopy(word) {
  const key = String(word || '').trim();
  return MOOD_CARD_COPY[key] || null;
}

export function getMoodGuide(word, fallback = '') {
  return getMoodCardCopy(word)?.guide || fallback || '';
}

export function getMoodQuestion(word, fallback = '') {
  return getMoodCardCopy(word)?.question
    || fallback
    || '这张卡，和你今天的心情有哪一处轻轻碰在一起？';
}
